#!/usr/bin/env python3
"""Build the chat folder of one group: chats/<group>/ with a link per project and a CLAUDE.md.

An agent opened in that folder sees every project of the group at once: one symlink per local
member project, `.claude/settings.local.json` granting Claude Code those paths and HQ
(`permissions.additionalDirectories`), and a CLAUDE.md pointing at the group page, its hub and
each project page. HQ's own CLAUDE.md sits two levels up, so its rules still apply.
Pure read of members. The folder is rebuilt on every run and stays out of git (`chats/` is
ignored); only the symlinks, CLAUDE.md and that one settings key are ours — other files and
settings keys (permissions Claude Code saved) are left as they are.

Usage: python3 scripts/hq_group_chat.py (--group NAME | --group-id ID) [--hq DIR]
Exit: 0 done (JSON report on stdout) · 3 registry.yaml unreadable · 4 no such group in the registry.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hq_registry import read_yaml_subset, slugify  # noqa: E402  (same folder)
from hq_sync import page_hub, page_title, read_text  # noqa: E402


def group_members(entries, group_id, group_name):
    """Registry entries of the group — by id first (it survives a rename), else by name."""
    if group_id:
        found = [e for e in entries if e.get("group_id") == group_id]
        if found:
            return found[0].get("group") or group_name, found
    if group_name:
        found = [e for e in entries if e.get("group") == group_name]
        if found:
            return group_name, found
    return None, []


def group_hub(hq, name, members, hubs):
    if hubs.get(name):
        return hubs[name]
    member_hubs = {h for h in (page_hub(hq, e["slug"]) for e in members) if h}
    return member_hubs.pop() if len(member_hubs) == 1 else None


def sync_links(folder, linkable, skipped):
    """One symlink per project; stale links of ours go, anything that is not a link stays."""
    changed = False
    wanted = {e["slug"]: e["path"] for e in linkable}
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if os.path.islink(path) and (name not in wanted or os.readlink(path) != wanted[name]):
            os.unlink(path)
            changed = True
    linked = []
    for slug, target in sorted(wanted.items()):
        path = os.path.join(folder, slug)
        if os.path.islink(path):
            linked.append(slug)
            continue
        if os.path.lexists(path):
            skipped[slug] = "name taken by a file in the chat folder"
            continue
        try:
            os.symlink(target, path, target_is_directory=True)
        except OSError as exc:  # e.g. Windows without symlink rights — the path is still granted
            skipped[slug] = f"not linked: {exc.strerror or exc}"
            continue
        linked.append(slug)
        changed = True
    return linked, changed


def render_claude_md(hq, name, slug, hub, members, linked, skipped):
    lines = [
        f"# {name} — group chat", "",
        "Generated by `scripts/hq_group_chat.py` each time the chat opens; edits here are overwritten.",
        f"This folder is a chat over the **{name}** group of HQ: its projects are linked here by name.", "",
        f"- **Group page:** `../../groups/{slug}.md`",
        f"- **Hub:** `{hub}` → `{hub}/wiki/index.md`" if hub else "- **Hub:** none — go from each project page to its own wiki",
        f"- **Projects ({len(members)}):**",
    ]
    for e in sorted(members, key=lambda e: e["slug"]):
        title = page_title(hq, e["slug"])
        where = f"`{e['slug']}/` → `{e['path']}`" if e["slug"] in linked else f"`{e['path']}` ({skipped.get(e['slug'], 'not linked')})"
        lines.append(f"  - {where} · page `../../projects/{e['slug']}.md`" + (f" — {title}" if title else ""))
    lines += [
        "", "## How to answer", "",
        "- Same route as HQ's CLAUDE.md two levels up: the group page → the project page → the hub →",
        "  the project's own `wiki/index.md` → the entity. Answer with links to every page you used.",
        "- A linked folder is the project itself. Read through it freely; a change to a project is made",
        "  in a session opened in that project, not from here.",
    ]
    return "\n".join(lines) + "\n"


def write_if_changed(path, text):
    if read_text(path) == text:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def sync_settings(folder, directories):
    """Own only permissions.additionalDirectories; keep what Claude Code saved in the same file."""
    path = os.path.join(folder, ".claude", "settings.local.json")
    try:
        settings = json.loads(read_text(path) or "{}")
    except ValueError:
        settings = {}
    if not isinstance(settings, dict):
        settings = {}
    permissions = settings.get("permissions") if isinstance(settings.get("permissions"), dict) else {}
    settings["permissions"] = {**permissions, "additionalDirectories": directories}
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return write_if_changed(path, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--hq", default=".", help="HQ root (default: cwd)")
    ap.add_argument("--group", help="group name as in registry.yaml")
    ap.add_argument("--group-id", help="group id as in registry.yaml (preferred: survives a rename)")
    args = ap.parse_args(argv)
    if not args.group and not args.group_id:
        ap.error("--group or --group-id is required")
    hq = os.path.abspath(args.hq)
    registry = os.path.join(hq, "registry.yaml")
    try:
        entries = read_yaml_subset(registry).get("projects") or []
        config = read_yaml_subset(os.path.join(hq, "hq.yaml"))
    except ValueError as exc:
        print(f"hq_group_chat: {exc}", file=sys.stderr)
        return 3
    if not os.path.exists(registry):
        print("hq_group_chat: no registry.yaml (run hq_registry.py first)", file=sys.stderr)
        return 3
    name, members = group_members(entries, args.group_id, args.group)
    if not members:
        print(f"hq_group_chat: no project of group {args.group_id or args.group!r} in registry.yaml", file=sys.stderr)
        return 4
    hubs = {h["group"]: os.path.abspath(os.path.expanduser(h["path"])) for h in (config.get("hubs") or [])
            if isinstance(h, dict) and h.get("group") and h.get("path")}

    skipped, linkable = {}, []
    for e in members:
        if (e.get("host") or "local") != "local":
            skipped[e["slug"]] = "on another host"
        elif not os.path.isdir(e.get("path") or ""):
            skipped[e["slug"]] = "path missing"
        else:
            linkable.append(e)
    slug = slugify(name)
    folder = os.path.join(hq, "chats", slug)
    os.makedirs(folder, exist_ok=True)
    linked, links_changed = sync_links(folder, linkable, skipped)
    hub = group_hub(hq, name, members, hubs)
    text = render_claude_md(hq, name, slug, hub, members, linked, skipped)
    md_changed = write_if_changed(os.path.join(folder, "CLAUDE.md"), text)
    directories = [hq] + [e["path"] for e in sorted(linkable, key=lambda e: e["slug"])]
    if hub and hub not in directories:
        directories.append(hub)
    settings_changed = sync_settings(folder, directories)
    print(json.dumps({
        "group": name, "path": folder, "linked": linked, "skipped": skipped,
        "changed": links_changed or md_changed or settings_changed,
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
